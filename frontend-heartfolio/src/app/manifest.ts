import type { MetadataRoute } from "next";

export default function manifest(): MetadataRoute.Manifest {
  return {
    name: "Heartfolio — Keep the Moment",
    short_name: "Heartfolio",
    description: "Turn a memory into a keepsake worth keeping forever.",
    start_url: "/",
    display: "standalone",
    background_color: "#F7F1E6",
    theme_color: "#141B2E",
    icons: [
      // SVG first for anything that supports it — it stays sharp at any size.
      { src: "/icon.svg", sizes: "any", type: "image/svg+xml" },
      // PNG fallbacks. Android's install prompt and splash screen require
      // real raster icons at these two sizes and will silently decline to
      // offer installation without them, which is a failure with no error
      // message anywhere.
      // 32px for desktop browsers and feed readers that will not take an
      // SVG. Regenerated by `node scripts/generate-icons.mjs`, never by
      // hand — see that script for why.
      { src: "/favicon-32x32.png", sizes: "32x32", type: "image/png", purpose: "any" },
      { src: "/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
      { src: "/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
      // `maskable` lets Android crop to its own shape without clipping the
      // mark; without it the launcher letterboxes the icon in a white box.
      { src: "/icon-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
    ],
  };
}
